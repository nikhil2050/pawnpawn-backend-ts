-- ----------------------------------------------------------------------------
-- Medusa compatibility migration (idempotent)
-- Convert legacy UUID primary keys to text IDs so Medusa-generated IDs
-- (seller_..., lineage_...) can be inserted. Existing UUID values cast to text.
-- ----------------------------------------------------------------------------
DO $$ BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'seller'
          AND column_name = 'id'
          AND data_type = 'uuid'
    ) THEN
        -- Views depend on these columns; drop and let the view section recreate them
        DROP VIEW IF EXISTS product_current_owner;
        DROP VIEW IF EXISTS seller_stats;

        ALTER TABLE product_lineage DROP CONSTRAINT IF EXISTS product_lineage_seller_id_fkey;
        ALTER TABLE seller ALTER COLUMN id DROP DEFAULT;
        ALTER TABLE seller ALTER COLUMN id TYPE TEXT USING id::text;
        ALTER TABLE product_lineage ALTER COLUMN id DROP DEFAULT;
        ALTER TABLE product_lineage ALTER COLUMN id TYPE TEXT USING id::text;
        ALTER TABLE product_lineage ALTER COLUMN seller_id TYPE TEXT USING seller_id::text;
        ALTER TABLE product_lineage
            ADD CONSTRAINT product_lineage_seller_id_fkey
            FOREIGN KEY (seller_id) REFERENCES seller(id);
    END IF;
END $$;

-- ============================================================================
-- PRODUCT TABLE EXTENSION
-- ============================================================================
-- Add listing_type column to Medusa's built-in 'product' table.
-- 
-- JAVA DEVELOPER NOTES:
--   - Medusa already has a 'product' table (managed by its internal ORM).
--   - We ALTER TABLE to add our custom column, similar to:
--     ALTER TABLE product ADD COLUMN listing_type VARCHAR(20) DEFAULT 'FIXED_PRICE'
--   - In a JPA/Hibernate project, you'd add a field to the Product entity:
--     @Enumerated(EnumType.STRING)
--     @Column(default = "FIXED_PRICE")
--     private ListingType listingType = ListingType.FIXED_PRICE;
--   - The DO $$ block checks if the table exists before altering (idempotent)
--   - If Medusa migrations haven't run yet, the product table won't exist,
--     so we catch undefined_table gracefully
DO $$ BEGIN
    ALTER TABLE product 
    ADD COLUMN IF NOT EXISTS listing_type product_listing_type NOT NULL DEFAULT 'FIXED_PRICE';
EXCEPTION
    WHEN undefined_table THEN
        -- Table doesn't exist yet (Medusa migrations not run).
        -- The column will be added after migrations complete.
        RAISE NOTICE 'Product table does not exist yet. listing_type column will be added by Medusa migrations.';
    WHEN duplicate_column THEN NULL;
END $$;

-- Index on listing_type for filtering products by type (FIXED_PRICE vs AUCTION)
-- Java: CREATE INDEX on listing_type column for fast queries
DO $$ BEGIN
    CREATE INDEX IF NOT EXISTS idx_product_listing_type ON product(listing_type);
EXCEPTION
    WHEN undefined_table THEN
        RAISE NOTICE 'Product table does not exist yet. Index will be created after migrations.';
END $$;

-- ============================================================================
-- HELPER VIEWS (Optional — for easier querying)
-- ============================================================================
-- SQL Views are like read-only DTO projections in Java (e.g., Spring Data JPA projections).
-- They don't store data; they provide a pre-defined query result.

-- View: Current owner of each product (latest lineage entry per product)
-- Java: SELECT ... ORDER BY transacted_at DESC with DISTINCT ON (like ROW_NUMBER() = 1)
CREATE OR REPLACE VIEW product_current_owner AS
SELECT DISTINCT ON (pl.product_id)
    pl.product_id,
    pl.seller_id,
    pl.buyer_id AS current_owner_id,
    pl.price AS last_sale_price,
    pl.transacted_at AS last_transacted_at
FROM product_lineage pl
ORDER BY pl.product_id, pl.transacted_at DESC;

-- View: Aggregated seller statistics (total sales, revenue, last sale)
-- Java: GROUP BY with COUNT, SUM, MAX aggregates
CREATE OR REPLACE VIEW seller_stats AS
SELECT 
    s.id,
    s.handle,
    s.store_name,
    s.verification_status,
    COUNT(pl.id) AS total_sales,
    COALESCE(SUM(pl.price), 0) AS total_revenue,
    MAX(pl.transacted_at) AS last_sale_at
FROM seller s
LEFT JOIN product_lineage pl ON s.id = pl.seller_id
GROUP BY s.id, s.handle, s.store_name, s.verification_status;
