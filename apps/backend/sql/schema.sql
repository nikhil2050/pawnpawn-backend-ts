-- ============================================================================
-- SELLER TABLE
-- ============================================================================
-- Stores marketplace seller information.
-- 
-- JAVA DEVELOPER NOTES:
--   - This is equivalent to a Java entity class annotated with @Entity
--   - id UUID PRIMARY KEY DEFAULT gen_random_uuid()  →  @Id @GeneratedValue (UUID)
--   - VARCHAR UNIQUE  →  @Column(unique = true)
--   - created_at / updated_at  →  @CreatedDate / @LastModifiedDate (JPA auditing)
--   - No Java class file exists for this table (raw SQL only, per requirements)
--   - If you later create a Medusa module for Seller, you'd map this table in TypeScript
CREATE TABLE IF NOT EXISTS seller (
    -- Primary key: text ID generated by Medusa (e.g. seller_01J...)
    -- Medusa modules use text IDs; the DB must match so service creates work.
    id TEXT PRIMARY KEY,

    -- Optional link to the Medusa customer account behind this seller.
    -- Nullable: celebrity/influencer sellers may not have a storefront account.
    -- Uniqueness is enforced by idx_seller_customer_id below.
    customer_id VARCHAR(255),

    -- Unique public handle/username for the seller
    -- Java: @Column(unique = true, nullable = false, length = 100)
    handle VARCHAR(100) NOT NULL UNIQUE,

    -- Display name of the seller's store
    -- Java: @Column(nullable = false, length = 255)
    store_name VARCHAR(255) NOT NULL,

    -- Optional avatar/profile image URL
    -- Java: @Column(length = 500)
    avatar_url VARCHAR(500),

    -- Razorpay Connect account ID for payouts (unique per seller)
    -- Java: @Column(unique = true, length = 100)
    razorpay_account_id VARCHAR(100) UNIQUE,

    -- Verification status: PENDING (default) or VERIFIED
    -- Java: @Enumerated(EnumType.STRING) with default = PENDING
    verification_status seller_verification_status NOT NULL DEFAULT 'PENDING',

    -- Trust level: trusted (default) or untrusted
    -- Most sellers start as trusted celebrities/influencers
    -- Java: @Enumerated(EnumType.STRING) with default = trusted
    seller_trust VARCHAR(20) NOT NULL DEFAULT 'trusted',

    -- Seller category: celebrity, influencer, musician, athlete, other
    -- Java: @Enumerated(EnumType.STRING) with default = celebrity
    seller_category VARCHAR(50) NOT NULL DEFAULT 'celebrity',

    -- Social media handle (Instagram, Twitter, etc.)
    -- Java: @Column(length = 255)
    social_media_handle VARCHAR(255),

    -- Seller biography/description
    -- Java: @Column(columnDefinition = "TEXT")
    bio TEXT,

    -- Creation timestamp (auto-set by database)
    -- Java: @CreatedDate
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Last update timestamp (auto-set by database)
    -- Java: @LastModifiedDate
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Soft-delete timestamp (Medusa generated queries filter on this)
    deleted_at TIMESTAMPTZ
);

