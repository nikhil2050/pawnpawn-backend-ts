-- ============================================================================
-- PRODUCT LINEAGE TABLE
-- ============================================================================
-- Tracks ownership history of products: seller → buyer → buyer → ...
-- Each row represents one transfer of ownership (a sale).
-- 
-- JAVA DEVELOPER NOTES:
--   - This is a join/association table tracking product ownership transfers
--   - product_id references Medusa's product table (stored as VARCHAR since Medusa uses text IDs)
--   - seller_id is a FOREIGN KEY to the seller table (like @ManyToOne in JPA)
--   - buyer_id is a Medusa customer ID (VARCHAR, not a FK to a local table)
CREATE TABLE IF NOT EXISTS product_lineage (
    -- Primary key: text ID generated by Medusa (e.g. lineage_01J...)
    id TEXT PRIMARY KEY,

    -- Reference to Medusa product ID (VARCHAR because Medusa product IDs are text)
    -- Java: @Column(nullable = false, length = 100)
    product_id VARCHAR(100) NOT NULL,

    -- Seller who listed/sold the product (FK to seller table).
    -- Nullable: a buyer-to-buyer resale has no seller row for the previous owner.
    seller_id TEXT REFERENCES seller(id) ON DELETE RESTRICT,

    -- Buyer who purchased the product (Medusa customer ID)
    -- Java: @Column(length = 100) — customer reference, no local FK
    buyer_id VARCHAR(100),

    -- Transaction price at time of sale (decimal with 2 places)
    -- Java: @Column(nullable = false, precision = 12, scale = 2) with BigDecimal
    price DECIMAL(12, 2) NOT NULL,

    -- When the transaction occurred (auto-set by database)
    -- Java: @CreatedDate
    transacted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Timestamps added automatically by Medusa's model layer
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Soft-delete timestamp (Medusa generated queries filter on this)
    deleted_at TIMESTAMPTZ
);

-- Index on product_id for querying a product's ownership history
CREATE INDEX IF NOT EXISTS idx_product_lineage_product ON product_lineage(product_id);

-- Index on seller_id for querying a seller's sales history
CREATE INDEX IF NOT EXISTS idx_product_lineage_seller ON product_lineage(seller_id);

-- Index on buyer_id for querying a buyer's purchase history
CREATE INDEX IF NOT EXISTS idx_product_lineage_buyer ON product_lineage(buyer_id);

-- Index on transacted_at for time-based queries (e.g., sales this month)
CREATE INDEX IF NOT EXISTS idx_product_lineage_transacted ON product_lineage(transacted_at);

-- Add soft-delete column for Medusa's generated queries (idempotent)
